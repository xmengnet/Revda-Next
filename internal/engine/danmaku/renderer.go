// Add buffers one message, after dropping glyphs libass cannot draw.
func (r *Renderer) Add(m *DanmakuMessage) {
	m.Text = CleanDanmakuText(m.Text)
	if m.Text == "" {
		return
	}
	r.mu.Lock()
	defer r.mu.Unlock()
	r.messages = append(r.messages, m)
	if len(r.messages) > r.maxHistory {
		r.messages = r.messages[len(r.messages)-r.maxHistory:]
	}
}

// WriteASS renders the accumulated messages into a complete ASS document.
// mpv's lavf ASS demuxer requires a finite, seekable file, so the consumer
// snapshots the whole document and reloads periodically.
func (r *Renderer) WriteASS() string {
	r.mu.Lock()
	msgs := make([]*DanmakuMessage, len(r.messages))
	copy(msgs, r.messages)
	laneBusy := make([]time.Time, len(r.laneBusy))
	copy(laneBusy, r.laneBusy)
	assZero := r.assZero
	r.mu.Unlock()

	var b strings.Builder
	fmt.Fprintf(&b, assHeader, r.fontSize, int(r.fontAlpha*255))
	for _, m := range msgs {
		if m.Time.Before(assZero) {
			continue // arrived before the player started rendering
		}
		fmt.Fprint(&b, r.formatOne(m, laneBusy, assZero))
	}
	return b.String()
}

// formatOne renders a single Dialogue line, updating the shared lane state.
func (r *Renderer) formatOne(m *DanmakuMessage, laneBusy []time.Time, assZero time.Time) string {
	pts := m.Time.Sub(assZero).Seconds()
	startStr := formatASSTime(pts)
	endStr := formatASSTime(pts + r.speedSec)

	alphaTag := fmt.Sprintf("{\\alpha&H%02X&}", int(r.fontAlpha*255))
	colorTag := ""
	if m.Color != "" && !strings.EqualFold(m.Color, "ffffff") && len(m.Color) == 6 {
		c := strings.ToLower(m.Color)
		// ASS wants &HBBGGRR
		colorTag = fmt.Sprintf("{\\1c&H%s%s%s&}", c[4:6], c[2:4], c[0:2])
	}

	if m.Position == 0 {
		lane := -1
		for i := range laneBusy {
			if m.Time.After(laneBusy[i]) {
				lane = i
				break
			}
		}
		if lane == -1 {
			lane = int(m.Time.UnixNano()) % len(laneBusy)
		}
		textWidth := float64(len([]rune(m.Text))) * float64(r.fontSize)
		busy := time.Duration(r.speedSec * (textWidth/1920.0 + 0.15) * float64(time.Second))
		laneBusy[lane] = m.Time.Add(busy)

		y := danmakuBaseY(r.areaPct, r.anchor) + lane*r.fontSize
		endX := -(textWidth + 50)
		return fmt.Sprintf("Dialogue: 0,%s,%s,Default,,0,0,0,,%s%s{\\move(1920,%d,%d,%d)}%s\n",
			startStr, endStr, alphaTag, colorTag, y, int(endX), y, escapeASSText(m.Text))
	}

	// centered (superchat etc.)
	return fmt.Sprintf("Dialogue: 0,%s,%s,Default,,0,0,0,,%s%s{\\an8}%s\n",
		startStr, endStr, alphaTag, colorTag, escapeASSText(m.Text))
}

func escapeASSText(s string) string {
	s = strings.ReplaceAll(s, "\\", "\\\\")
	s = strings.ReplaceAll(s, "{", "\\{")
	s = strings.ReplaceAll(s, "}", "\\}")
	s = strings.ReplaceAll(s, "\n", " ")
	return s
}

func formatASSTime(sec float64) string {
	if sec < 0 {
		sec = 0
	}
	h := int(sec) / 3600
	m := (int(sec) % 3600) / 60
	s := int(sec) % 60
	cs := int((sec - float64(int(sec))) * 100)
	return fmt.Sprintf("%d:%02d:%02d.%02d", h, m, s, cs)
}

// StartHTTP serves the renderer as a snapshot ASS file on a local HTTP URL,
// suitable for mpv's --sub-file (finite content, seekable). It also pumps
// messages from a danmaku client channel into the renderer.
func StartHTTP(ctx context.Context, messages <-chan *DanmakuMessage, r *Renderer) (string, error) {
	mux := http.NewServeMux()
	mux.HandleFunc("/danmaku.ass", func(w http.ResponseWriter, req *http.Request) {
		body := r.WriteASS()
		w.Header().Set("Content-Type", "text/x-ssa")
		w.Header().Set("Content-Length", fmt.Sprint(len(body)))
		w.Header().Set("Access-Control-Allow-Origin", "*")
		_, _ = w.Write([]byte(body))
	})

	ln, err := net.Listen("tcp", "127.0.0.1:0")
	if err != nil {
		return "", err
	}
	srv := &http.Server{Handler: mux}

	go func() {
		<-ctx.Done()
		shutdownCtx, cancel := context.WithTimeout(context.Background(), 2*time.Second)
		defer cancel()
		_ = srv.Shutdown(shutdownCtx)
	}()
	go func() { _ = srv.Serve(ln) }()

	go func() {
		for {
			select {
			case <-ctx.Done():
				return
			case m := <-messages:
				if m == nil {
					return
				}
				r.Add(m)
			}
		}
	}()

	return fmt.Sprintf("http://%s/danmaku.ass", ln.Addr().String()), nil
}
