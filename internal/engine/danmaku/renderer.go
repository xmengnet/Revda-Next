// Renderer accumulates danmaku messages and renders them as a complete ASS
// subtitle document. Consumers snapshot it via WriteASS.
type Renderer struct {
	mu        sync.Mutex
	fontSize  int
	fontAlpha float64
	speedSec  float64
	areaPct   int
	anchor    int
	assZero   time.Time // wall-clock instant that maps to mpv playback time 0

	messages   []*DanmakuMessage
	laneBusy   []time.Time
	maxHistory int
}

// NewRenderer creates an ASS renderer matching the dmlive defaults. speedMs
// is the danmaku screen-crossing duration in milliseconds (the unit the Rust
// dmlive config uses). areaPct caps the screen height the lanes may use and
// anchor places that area (top, middle or bottom).
func NewRenderer(fontScale, fontAlpha float64, speedMs int, areaPct int, anchor string) *Renderer {
	if fontScale <= 0 {
		fontScale = 1.0
	}
	if fontAlpha < 0 || fontAlpha > 1 {
		fontAlpha = 0
	}
	speedSec := speedMs / 1000
	if speedSec < 4 {
		speedSec = 8
	} else if speedSec > 30 {
		speedSec = 30
	}
	fontSize := int(40 * fontScale)
	numLanes := danmakuChannelNum(fontSize, areaPct)
	return &Renderer{
		fontSize:   fontSize,
		fontAlpha:  fontAlpha,
		speedSec:   float64(speedSec),
		areaPct:    clampDanmakuArea(areaPct),
		anchor:     anchorIndex(anchor),
		assZero:    time.Now(),
		laneBusy:   make([]time.Time, numLanes),
		maxHistory: 3000, // ~10h at 5 msg/min; keeps memory bounded
	}
}

// SetClock recalibrates the ASS timeline: anchor is the wall-clock instant the
// player is currently rendering as time-pos 0. Callers derive it from mpv's
// time-pos (anchor = now - pos) so danmaku land on the video's clock instead
// of the wall clock, absorbing startup delay and buffering.
func (r *Renderer) SetClock(anchor time.Time) {
	r.mu.Lock()
	r.assZero = anchor
	r.mu.Unlock()
}

// HasContent reports whether at least one message has been buffered.
func (r *Renderer) HasContent() bool {
	r.mu.Lock()
	defer r.mu.Unlock()
	return len(r.messages) > 0
}

